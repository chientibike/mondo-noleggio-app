const DICTS: Record<Lang, Record<TKey, string>> = { it, en };

let current: Lang = "it";
export const getLang = () => current;

// Non-hook translate, for helpers outside components. Components use useI18n().t
// so they re-render when the language changes.
export function tr(key: TKey, vars?: Record<string, string | number>) {
  let s = DICTS[current][key] ?? it[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.replace(`{${k}}`, String(vars[k]));
  return s;
}

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: typeof tr };
const I18nCtx = createContext<Ctx>({ lang: "it", setLang: () => {}, t: tr });

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("it");
  current = lang;

  useEffect(() => {
    storage.getItem(LANG_KEY, "it" as string).then((v) => {
      if (v === "en" || v === "it") setLangState(v);
    });
  }, []);

  const setLang = useCallback((l: Lang) => {
    current = l;
    setLangState(l);
    storage.setItem(LANG_KEY, l);
  }, []);

  // `t` changes identity with lang so memoized consumers refresh.
  const t = useCallback((key: TKey, vars?: Record<string, string | number>) => tr(key, vars), 
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [lang]);

  return <I18nCtx.Provider value={{ lang, setLang, t }}>{children}</I18nCtx.Provider>;
}

export const useI18n = () => useContext(I18nCtx);
